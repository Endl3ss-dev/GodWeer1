package swerve.acd;

/**
 * Насколько надёжно установлено событие и его категория.
 *
 * <p>Разделение принципиальное: клиент видит только то, что сервер сам прислал.
 * Поэтому «сервер прислал текст» — факт, а «этот текст означает флаг античита» —
 * вывод по шаблону. Второе никогда не выдаётся за первое: {@link AcdFormatter}
 * печатает уровень достоверности у каждой записи, а {@link AcdReport} считает
 * предположения отдельной строкой в сводке.
 */
public enum AcdConfidence {

    /**
     * Источник прямо утверждает тип события: пакет отключения, пакет коррекции
     * позиции, объявленный сервером бренд, ошибка обработки пакета.
     */
    CONFIRMED("Подтверждено источником"),

    /**
     * Факт, измеренный самим клиентом: расстояние отката, скорость, выданная
     * сервером, время жизни соединения. Причина события при этом неизвестна.
     */
    OBSERVED("Измерено клиентом"),

    /**
     * Совпадение с правилом распознавания в тексте сообщения. Категория
     * предположительная: тот же текст мог быть чатом игрока, плагином или админом.
     */
    HEURISTIC("Предположение по шаблону");

    private final String label;

    AcdConfidence(String label) {
        this.label = label;
    }

    public String label() {
        return this.label;
    }

    /** Нужно ли помечать запись как недоказанную (сводка, фильтры, предупреждение в отчёте). */
    public boolean speculative() {
        return this == HEURISTIC;
    }
}
