package swerve.script;

/**
 * Форма блока — от неё зависит и отрисовка, и правила вложения.
 */
public enum BlockShape {

    /** Шляпа: с неё начинается функция (событие). */
    HAT,

    /** Обычный блок стека. */
    STACK,

    /** Блок с «пастью»: внутри лежит ещё один стек (цикл, условие). */
    C
}
