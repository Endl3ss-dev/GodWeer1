  if ($mixin -notmatch [regex]::Escape($name)) {
    $mixin = $mixin.Replace($anchor, $anchor + "`r`n    `"$name`",")
  }
}
[IO.File]::WriteAllText($mixinPath, $mixin, (New-Object Text.UTF8Encoding($false)))

